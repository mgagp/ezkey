-- ============================================================================
-- Ezkey Migration V24: Partition ezkey_audit_log by Month
-- ============================================================================
-- Description: Converts ezkey_audit_log table to monthly range partitioning
--              for improved query performance, efficient data archival, and
--              SOC2 compliance support.
--
-- Context: High-volume table that will grow rapidly in production. Monthly
--          partitioning enables efficient partition pruning for date-range
--          queries, simplifies compliance reporting, and supports 7-year
--          retention requirements for SOC2.
--
-- Development Mode: This migration assumes an empty or non-existent table.
--                   No data migration is performed.
--
-- Author: Ezkey contributors
-- Date: 2025-01-XX
-- ============================================================================

-- ============================================================================
-- STEP 1: Drop Existing Table (if exists)
-- ============================================================================

-- Drop existing table and all its dependencies (indexes, constraints)
-- In development mode, this is safe as there's no data to preserve
DROP TABLE IF EXISTS ezkey_audit_log CASCADE;

-- ============================================================================
-- STEP 2: Create Partitioned Table Structure
-- ============================================================================

-- Create partitioned table directly with final name
CREATE TABLE ezkey_audit_log (
    audit_log_id BIGINT GENERATED ALWAYS AS IDENTITY,

    -- Event classification
    event_type VARCHAR(50) NOT NULL,
    event_action VARCHAR(100) NOT NULL,
    event_status VARCHAR(20) NOT NULL CHECK (event_status IN ('SUCCESS', 'FAILURE', 'ERROR')),

    -- API identification
    api_name VARCHAR(50) NOT NULL CHECK (api_name IN ('ADMIN_API', 'AUTH_API', 'M2M_API')),

    -- Network information
    ip_address VARCHAR(45),
    user_agent TEXT,

    -- Entity references (nullable for flexibility)
    admin_id INT REFERENCES ezkey_admin(admin_id) ON DELETE SET NULL,
    integration_id INT REFERENCES ezkey_integration(integration_id) ON DELETE SET NULL,
    enrollment_id INT REFERENCES ezkey_enrollment(enrollment_id) ON DELETE SET NULL,
    auth_attempt_id INT,
    auth_attempt_created_at TIMESTAMPTZ,
    tenant_id INT REFERENCES ezkey_tenant(tenant_id) ON DELETE SET NULL,
    -- Foreign key to partitioned table requires composite key reference
    -- PostgreSQL requires FK to partitioned table to reference composite primary key
    FOREIGN KEY (auth_attempt_id, auth_attempt_created_at)
        REFERENCES ezkey_auth_attempt(auth_attempt_id, created_at)
        ON DELETE SET NULL,

    -- Event details and errors
    event_details TEXT,
    error_message TEXT,

    -- Timestamp (partitioning key)
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
) PARTITION BY RANGE (created_at);


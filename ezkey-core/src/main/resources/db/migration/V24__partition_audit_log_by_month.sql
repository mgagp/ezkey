-- ============================================================================
-- STEP 3: Create Initial Partitions
-- ============================================================================

-- Create partition for current month
-- Note: Using first day of current month to first day of next month
DO $$
DECLARE
    current_month_start TIMESTAMPTZ;
    next_month_start TIMESTAMPTZ;
    partition_name TEXT;
BEGIN
    -- Calculate current month boundaries (using TIMESTAMPTZ for partition boundaries)
    current_month_start := DATE_TRUNC('month', CURRENT_TIMESTAMP);
    next_month_start := current_month_start + INTERVAL '1 month';

    -- Create partition name (e.g., ezkey_audit_log_2025_01)
    partition_name := 'ezkey_audit_log_' || TO_CHAR(current_month_start, 'YYYY_MM');

    -- Create partition for current month
    EXECUTE format(
        'CREATE TABLE %I PARTITION OF ezkey_audit_log FOR VALUES FROM (%L) TO (%L)',
        partition_name,
        current_month_start,
        next_month_start
    );

    -- Create partition for next month (pre-create for seamless transition)
    partition_name := 'ezkey_audit_log_' || TO_CHAR(next_month_start, 'YYYY_MM');
    EXECUTE format(
        'CREATE TABLE %I PARTITION OF ezkey_audit_log FOR VALUES FROM (%L) TO (%L)',
        partition_name,
        next_month_start,
        next_month_start + INTERVAL '1 month'
    );
END $$;

-- ============================================================================
-- STEP 4: Create Indexes on Partitioned Table
-- ============================================================================

-- Index for event type queries (most common filter)
-- This index will be created locally on each partition
CREATE INDEX idx_audit_log_event_type
ON ezkey_audit_log(event_type);

-- Index for status queries (security monitoring)
CREATE INDEX idx_audit_log_status
ON ezkey_audit_log(event_status);

-- Index for IP address queries (forensic analysis)
CREATE INDEX idx_audit_log_ip_address
ON ezkey_audit_log(ip_address);

-- Index for date range queries (compliance reporting)
CREATE INDEX idx_audit_log_created_at
ON ezkey_audit_log(created_at DESC);

-- Composite index for API + event type queries
CREATE INDEX idx_audit_log_api_event
ON ezkey_audit_log(api_name, event_type);

-- Index for enrollment tracking
CREATE INDEX idx_audit_log_enrollment
ON ezkey_audit_log(enrollment_id)
WHERE enrollment_id IS NOT NULL;

-- Index for admin tracking
CREATE INDEX idx_audit_log_admin
ON ezkey_audit_log(admin_id, created_at DESC)
WHERE admin_id IS NOT NULL;

-- JSONB GIN indexes for encryption operations (added by V19)
-- These indexes enable efficient queries on event_details JSONB field
CREATE INDEX idx_audit_encryption_key_id
ON ezkey_audit_log
USING GIN ((event_details::jsonb))
WHERE event_type IN ('KEY_INTRODUCED', 'KEY_PROMOTED_PRIMARY', 'KEY_DEMOTED', 'KEY_DISABLED');

CREATE INDEX idx_audit_reencryption_batch_id
ON ezkey_audit_log
USING GIN ((event_details::jsonb))
WHERE event_type IN ('REENCRYPTION_STARTED', 'REENCRYPTION_COMPLETED', 'REENCRYPTION_FAILED',
                     'REENCRYPTION_PAUSED', 'REENCRYPTION_RESUMED', 'REENCRYPTION_BATCH_PROGRESS');


-- Ezkey Migration V23: Partition ezkey_auth_attempt by Month
-- ============================================================================
-- Description: Converts ezkey_auth_attempt table to monthly range partitioning
--              for improved query performance and efficient data archival.
-- 
-- Context: High-volume table that will grow rapidly in production. Monthly
--          partitioning enables efficient partition pruning for date-range
--          queries and simplifies data lifecycle management.
--
-- Development Mode: This migration assumes an empty or non-existent table.
--                   No data migration is performed.
--
-- Author: Ezkey contributors
-- Date: 2025-01-XX
-- ============================================================================

-- ============================================================================
-- STEP 1: Drop Existing Table (if exists)
-- ============================================================================

-- Drop existing table and all its dependencies (indexes, constraints)
-- In development mode, this is safe as there's no data to preserve
DROP TABLE IF EXISTS ezkey_auth_attempt CASCADE;

-- ============================================================================
-- STEP 2: Create Partitioned Table Structure
-- ============================================================================

-- Create partitioned table directly with final name
-- Note: Includes columns added by V12 (encryption hash columns)
CREATE TABLE ezkey_auth_attempt (
    auth_attempt_id INT GENERATED ALWAYS AS IDENTITY,
    enrollment_id INT NOT NULL REFERENCES ezkey_enrollment(enrollment_id),
    auth_attempt_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' 
        CHECK (auth_attempt_status IN ('PENDING', 'READ', 'INVALID', 'REJECTED', 'ACCEPTED', 'EXPIRED')),
    auth_attempt_challenge INT,
    auth_attempt_proof_token TEXT NOT NULL,  -- Encrypted proof token (added by V12)
    auth_attempt_proof_token_hash VARCHAR(128),  -- Hash for deterministic lookup (added by V12)
    device_proof_token TEXT,  -- Encrypted device proof token (added by V12)
    device_proof_token_hash VARCHAR(128),  -- Hash for deterministic lookup (added by V12)
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '120 seconds'),
    -- Primary key composite required for partitioned tables
    -- PostgreSQL requires UNIQUE constraints to include partition key (created_at)
    PRIMARY KEY (auth_attempt_id, created_at)
) PARTITION BY RANGE (created_at);


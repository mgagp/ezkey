-- ============================================================================
-- STEP 3: Create Initial Partitions
-- ============================================================================

-- Create partition for current month
-- Note: Using first day of current month to first day of next month
DO $$
DECLARE
    current_month_start TIMESTAMPTZ;
    next_month_start TIMESTAMPTZ;
    partition_name TEXT;
BEGIN
    -- Calculate current month boundaries (using TIMESTAMPTZ for partition boundaries)
    current_month_start := DATE_TRUNC('month', CURRENT_TIMESTAMP);
    next_month_start := current_month_start + INTERVAL '1 month';
    
    -- Create partition name (e.g., ezkey_auth_attempt_2025_01)
    partition_name := 'ezkey_auth_attempt_' || TO_CHAR(current_month_start, 'YYYY_MM');
    
    -- Create partition for current month
    EXECUTE format(
        'CREATE TABLE %I PARTITION OF ezkey_auth_attempt FOR VALUES FROM (%L) TO (%L)',
        partition_name,
        current_month_start,
        next_month_start
    );
    
    -- Create partition for next month (pre-create for seamless transition)
    partition_name := 'ezkey_auth_attempt_' || TO_CHAR(next_month_start, 'YYYY_MM');
    EXECUTE format(
        'CREATE TABLE %I PARTITION OF ezkey_auth_attempt FOR VALUES FROM (%L) TO (%L)',
        partition_name,
        next_month_start,
        next_month_start + INTERVAL '1 month'
    );
END $$;

-- ============================================================================
-- STEP 4: Create Indexes on Partitioned Table
-- ============================================================================

-- Index for enrollment queries with created_at (supersession queries)
-- This index will be created locally on each partition
CREATE INDEX idx_auth_attempt_enrollment_created 
ON ezkey_auth_attempt(enrollment_id, created_at DESC);

-- Index for expiration cleanup jobs
-- Note: Cannot use CURRENT_TIMESTAMP in partial index predicate (not IMMUTABLE)
-- The index will still be efficient for cleanup queries with WHERE expires_at < NOW()
CREATE INDEX idx_auth_attempt_expires_at 
ON ezkey_auth_attempt(expires_at);

-- Index for status filtering
CREATE INDEX idx_auth_attempt_status 
ON ezkey_auth_attempt(auth_attempt_status);

-- Unique indexes on hash columns (added by V12)
-- Note: PostgreSQL requires UNIQUE constraints on partitioned tables to include partition key
-- Including created_at ensures global uniqueness while satisfying PostgreSQL's requirement
-- Hash collisions across partitions are extremely unlikely (SHA-256)
CREATE UNIQUE INDEX uq_auth_attempt_proof_token_hash 
ON ezkey_auth_attempt(auth_attempt_proof_token_hash, created_at) 
WHERE auth_attempt_proof_token_hash IS NOT NULL;

CREATE UNIQUE INDEX uq_auth_attempt_device_proof_token_hash 
ON ezkey_auth_attempt(device_proof_token_hash, created_at) 
WHERE device_proof_token_hash IS NOT NULL;


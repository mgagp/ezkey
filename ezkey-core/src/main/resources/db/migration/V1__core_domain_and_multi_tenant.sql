-- Authentication attempt table: represents individual MFA authentication requests and their lifecycle
-- Each auth attempt uses one-time proof tokens for replay attack prevention
-- Tracks complete authentication flow from creation through device response
-- Security-critical table with automatic expiration and state tracking
CREATE TABLE ezkey_auth_attempt (
    auth_attempt_id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    enrollment_id INT NOT NULL REFERENCES ezkey_enrollment(enrollment_id),  -- Parent enrollment that will handle this authentication request
    auth_attempt_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (auth_attempt_status IN ('PENDING', 'READ', 'INVALID', 'REJECTED', 'ACCEPTED', 'EXPIRED')),  -- Authentication attempt lifecycle status tracking
    auth_attempt_challenge INT,  -- Optional numeric challenge (4-6 digits) that user must enter on mobile device for additional security
    auth_attempt_proof_token TEXT NOT NULL,  -- Unique one-time token for this auth attempt - prevents replay attacks and ensures request authenticity
    device_proof_token TEXT,  -- Token generated by mobile device proving it received the auth_attempt_proof_token (cryptographic proof of possession)
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- Audit timestamp with timezone for auth attempt creation (immutable)
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '120 seconds')  -- Automatic expiration time with timezone - auth attempts expire after 2 minutes for security
);

-- Add table-level comment
COMMENT ON TABLE ezkey_auth_attempt IS 'Authentication attempt table tracking individual MFA requests from creation through completion. Uses one-time proof tokens to prevent replay attacks and includes automatic expiration for security. Each attempt represents a single authentication event requiring mobile device verification.';


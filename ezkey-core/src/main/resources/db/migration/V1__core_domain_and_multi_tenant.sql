-- Device enrollment table: represents the binding between an integration, user, and their mobile device
-- Each enrollment establishes a cryptographic relationship using Ed25519 key pairs
-- Contains state tracking for enrollment lifecycle and authentication configuration
-- Security-critical table containing cryptographic keys and proof tokens
-- NOTE: Migration V15 updates comments to reflect Ed25519 instead of RSA-2048
CREATE TABLE ezkey_enrollment (
    enrollment_id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    integration_id INT NOT NULL REFERENCES ezkey_integration(integration_id),  -- Parent integration this enrollment belongs to
    enrollment_name VARCHAR(64) NOT NULL,  -- Human-readable name for this enrollment (e.g., "John's iPhone", "Marketing Team Device")
    enrollment_status VARCHAR(20) NOT NULL DEFAULT 'CREATED' CHECK (enrollment_status IN ('CREATED', 'BOUND', 'VERIFIED', 'INVALID', 'REVOKED')),  -- Enrollment lifecycle status tracking
    enrollment_active BOOLEAN NOT NULL DEFAULT FALSE,  -- Operational flag controlling if this enrollment can be used for authentication
    enrollment_challenge INT DEFAULT NULL,  -- Optional numeric challenge for additional security during enrollment binding
    enrollment_proof_token TEXT NOT NULL,  -- Unique cryptographic token proving device received enrollment details (one-time use)
    auth_attempt_challenge_required BOOLEAN NOT NULL DEFAULT FALSE,  -- Configuration flag - if TRUE, authentication attempts require numeric challenge entry
    integration_private_key TEXT NOT NULL,  -- Ed25519 private key seed for integration-side cryptographic operations (32 bytes raw, Base64 encoded, encrypted at rest)
    integration_public_key TEXT NOT NULL,  -- Ed25519 public key for integration-side verification (32 bytes raw, Base64 encoded, safe to expose)
    device_public_key TEXT,  -- Ed25519 public key from mobile device for signature verification (32 bytes raw, Base64 encoded, set during binding)
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL  -- Audit timestamp with timezone for enrollment creation (immutable)

COMMENT ON COLUMN ezkey_audit_log.event_status IS 'Outcome of the event: SUCCESS (completed successfully), FAILURE (operation failed), ERROR (system error occurred)';
COMMENT ON COLUMN ezkey_audit_log.api_name IS 'API that generated this audit event: ADMIN_API (organization-facing) or AUTH_API (mobile device-facing)';
COMMENT ON COLUMN ezkey_audit_log.endpoint_path IS 'Full REST endpoint path that was accessed (e.g., /api/v1/auth-attempts/pending)';
COMMENT ON COLUMN ezkey_audit_log.http_method IS 'HTTP method used: GET, POST, PUT, DELETE, PATCH';

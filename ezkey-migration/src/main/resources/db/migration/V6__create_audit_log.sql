COMMENT ON COLUMN ezkey_audit_log.created_at IS 'Timestamp when the event occurred - immutable audit timestamp for compliance and forensic analysis';

-- Performance indexes for common audit queries
CREATE INDEX idx_audit_log_created_at ON ezkey_audit_log(created_at DESC);  -- Time-based queries and retention cleanup
CREATE INDEX idx_audit_log_event_type ON ezkey_audit_log(event_type, created_at DESC);  -- Filter by event category
CREATE INDEX idx_audit_log_admin ON ezkey_audit_log(admin_id, created_at DESC) WHERE admin_id IS NOT NULL;  -- Admin activity tracking
CREATE INDEX idx_audit_log_enrollment ON ezkey_audit_log(enrollment_id, created_at DESC) WHERE enrollment_id IS NOT NULL;  -- Enrollment lifecycle tracking
CREATE INDEX idx_audit_log_auth_attempt ON ezkey_audit_log(auth_attempt_id, created_at DESC) WHERE auth_attempt_id IS NOT NULL;  -- Authentication attempt tracking
CREATE INDEX idx_audit_log_ip_address ON ezkey_audit_log(ip_address, created_at DESC) WHERE ip_address IS NOT NULL;  -- IP-based security analysis
CREATE INDEX idx_audit_log_status ON ezkey_audit_log(event_status, created_at DESC);  -- Filter by success/failure
CREATE INDEX idx_audit_log_api_endpoint ON ezkey_audit_log(api_name, endpoint_path, created_at DESC);  -- API endpoint usage analysis

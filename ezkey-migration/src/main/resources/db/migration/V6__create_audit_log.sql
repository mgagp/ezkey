-- This migration creates comprehensive audit logging infrastructure for SOC2 compliance
-- and security monitoring of all critical operations in the Ezkey system

-- Audit log table: tracks all security-relevant events across admin-api and auth-api
-- Designed for comprehensive audit trail supporting SOC2 certification requirements
-- Includes IP address, user agent, request/response details for forensic analysis
CREATE TABLE ezkey_audit_log (
    audit_log_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    
    -- Event Classification
    event_type VARCHAR(50) NOT NULL,  -- Event category: AUTH, ENROLLMENT, INTEGRATION, ADMIN_AUTH, etc.
    event_action VARCHAR(100) NOT NULL,  -- Specific action: LOGIN, CREATE, BIND, VERIFY, APPROVE, DENY, etc.
    event_status VARCHAR(20) NOT NULL CHECK (event_status IN ('SUCCESS', 'FAILURE', 'ERROR')),  -- Outcome of the event
    
    -- API Identification
    api_name VARCHAR(50) NOT NULL CHECK (api_name IN ('ADMIN_API', 'AUTH_API')),  -- Which API generated this event
    endpoint_path VARCHAR(255),  -- Full endpoint path (e.g., /api/v1/auth-attempts)
    http_method VARCHAR(10),  -- HTTP method: GET, POST, PUT, DELETE
    
    -- Network and Client Information
    ip_address VARCHAR(45),  -- IPv4 or IPv6 address of the client
    user_agent TEXT,  -- Browser/client user agent string for device identification
    
    -- Entity References
    admin_id INT,  -- Reference to ezkey_admin if admin action
    integration_id INT,  -- Reference to ezkey_integration if integration-related
    enrollment_id INT,  -- Reference to ezkey_enrollment if enrollment-related
    auth_attempt_id INT,  -- Reference to ezkey_auth_attempt if auth-related
    tenant_id INT,  -- Reference to ezkey_tenant for multi-tenancy tracking
    
    -- Event Details
    event_details TEXT,  -- JSON or text with additional context about the event
    error_message TEXT,  -- Error details if event_status is FAILURE or ERROR
    
    -- Timestamps
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- When the event occurred
    
    -- Foreign key constraints (nullable to allow auditing even if entities are deleted)
    CONSTRAINT fk_audit_admin FOREIGN KEY (admin_id) REFERENCES ezkey_admin(admin_id) ON DELETE SET NULL,
    CONSTRAINT fk_audit_integration FOREIGN KEY (integration_id) REFERENCES ezkey_integration(integration_id) ON DELETE SET NULL,
    CONSTRAINT fk_audit_enrollment FOREIGN KEY (enrollment_id) REFERENCES ezkey_enrollment(enrollment_id) ON DELETE SET NULL,
    CONSTRAINT fk_audit_auth_attempt FOREIGN KEY (auth_attempt_id) REFERENCES ezkey_auth_attempt(auth_attempt_id) ON DELETE SET NULL,
    CONSTRAINT fk_audit_tenant FOREIGN KEY (tenant_id) REFERENCES ezkey_tenant(tenant_id) ON DELETE SET NULL
);

-- Add table-level comment
COMMENT ON TABLE ezkey_audit_log IS 'Comprehensive audit log for all security-relevant events across Ezkey APIs. Tracks authentication, enrollment, and administrative actions with full context for SOC2 compliance and security forensics. Retention policy managed by scheduled cleanup jobs.';


/**
 * Writes app/data/thirdPartyLicenses.json from package.json "dependencies" only
 * (runtime third-party packages shipped with the app). Re-run after dependency changes.
 *
 * Usage: node scripts/generate-third-party-licenses.mjs
 */
import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');

function readPackageMeta(depName) {
  const segments = depName.split('/');
  const pkgPath = path.join(root, 'node_modules', ...segments, 'package.json');
  return JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
}

function normalizeLicense(lic) {
  if (lic == null) {
    return 'Unknown';
  }
  if (typeof lic === 'string') {
    return lic;
  }
  if (typeof lic === 'object' && lic.type) {
    return String(lic.type);
  }
  return 'Unknown';
}

function main() {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const names = Object.keys(pkg.dependencies ?? {}).sort((a, b) => a.localeCompare(b));
  const packages = [];
  for (const name of names) {
    try {
      const meta = readPackageMeta(name);
      packages.push({
        name,
        version: meta.version ?? '',
        license: normalizeLicense(meta.license ?? meta.licenses),
      });
    } catch {
      packages.push({name, version: '', license: 'Unknown'});
    }
  }

  const out = {
    generatedAt: new Date().toISOString(),
    note: 'Generated by scripts/generate-third-party-licenses.mjs from package.json dependencies.',
    packages,
  };
  const outPath = path.join(root, 'app', 'data', 'thirdPartyLicenses.json');
  fs.mkdirSync(path.dirname(outPath), {recursive: true});
  fs.writeFileSync(outPath, `${JSON.stringify(out, null, 2)}\n`, 'utf8');
  console.log(`Wrote ${packages.length} packages to ${path.relative(root, outPath)}`);
}

main();
